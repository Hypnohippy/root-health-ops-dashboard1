// Deterministic SQL rendering from catalog metadata, never from application guesses.
const fs = require('node:fs');
const path = require('node:path');
const root = __dirname;
const c = JSON.parse(fs.readFileSync(path.join(root, 'source/catalog.json')));
const e = JSON.parse(fs.readFileSync(path.join(root, 'source/extra.json')));
const q = s => '"' + s.replaceAll('"', '""') + '"';
const lit = s => s == null ? 'NULL' : "'" + String(s).replaceAll("'", "''") + "'";
const name = o => `${q(o.schema)}.${q(o.name)}`;
const role = s => s === 'PUBLIC' ? 'PUBLIC' : q(s);
const app = s => s === 'public';
const seqOptions = s => `START WITH ${s.start} INCREMENT BY ${s.increment} MINVALUE ${s.min} MAXVALUE ${s.max} CACHE ${s.cache} ${s.cycle ? 'CYCLE' : 'NO CYCLE'}`;
const terminate = s => s.trim().replace(/;?$/, ';');
const managedPublicDefault = d => d.owner === 'supabase_admin' && d.schema === 'public';
// Compare effective entries, not grantor OIDs or catalog array order.
const normalizedAcl = expression => `SELECT coalesce(jsonb_agg(entry ORDER BY entry COLLATE "C"), '[]'::jsonb)
 FROM (SELECT (CASE WHEN x.grantee=0 THEN 'PUBLIC' ELSE pg_catalog.pg_get_userbyid(x.grantee) END)
  || ':' || x.privilege_type || ':' || x.is_grantable::text AS entry
  FROM pg_catalog.aclexplode(${expression}) x) entries`;
function managedDefaultAssertion(d) {
  const defaultKind = d.type === 'S' ? 's' : d.type; // pg_default_acl uses S; acldefault uses s.
  const expected = JSON.stringify((d.acl || []).map(a => `${a.grantee}:${a.privilege}:${a.grantable}`).sort());
  const schemaAcl = `coalesce((SELECT defaclacl FROM pg_catalog.pg_default_acl
   WHERE defaclrole=role_id AND defaclnamespace='public'::regnamespace AND defaclobjtype=${lit(d.type)}), '{}'::aclitem[])`;
  const globalAcl = `coalesce((SELECT defaclacl FROM pg_catalog.pg_default_acl
   WHERE defaclrole=role_id AND defaclnamespace=0 AND defaclobjtype=${lit(d.type)}), pg_catalog.acldefault(${lit(defaultKind)},role_id))`;
  return `DO $managed_default_acl$
DECLARE role_id oid := pg_catalog.to_regrole('supabase_admin'); actual jsonb; expected jsonb;
BEGIN
 IF role_id IS NULL THEN RAISE EXCEPTION 'Managed default ACL role unavailable'; END IF;
 ${normalizedAcl(schemaAcl)} INTO actual;
 IF actual IS DISTINCT FROM ${lit(expected)}::jsonb THEN
  RAISE EXCEPTION 'Managed public default ACL ${d.type} differs from the captured contract';
 END IF;
 -- Production has no custom global defaults for this role. Per-schema defaults
 -- are additive, so a broadened global ACL must not pass this assertion.
 ${normalizedAcl(globalAcl)} INTO actual;
 ${normalizedAcl(`pg_catalog.acldefault(${lit(defaultKind)},role_id)`)} INTO expected;
 IF actual IS DISTINCT FROM expected THEN
  RAISE EXCEPTION 'Managed global default ACL ${d.type} differs from the captured contract';
 END IF;
END $managed_default_acl$;`;
}
function acl(kind, target, entries) {
  const grantees = new Set(['PUBLIC', ...e.roles.map(r => r.name)]);
  return [
    ...[...grantees].map(r => `REVOKE ALL ON ${kind} ${target} FROM ${role(r)};`),
    ...(entries || []).map(a => `GRANT ${a.privilege} ON ${kind} ${target} TO ${role(a.grantee)}${a.grantable ? ' WITH GRANT OPTION' : ''};`),
  ];
}
function tableSQL(t) {
  const cols = t.columns.map(a => {
    let sql = `${q(a.name)} ${a.type}`;
    if (a.collation) sql += ` COLLATE ${a.collation}`;
    if (a.identity) {
      const s = c.sequences.find(s => s.table_schema === t.schema && s.table === t.name && s.column === a.name);
      if (!s || s.dependency !== 'i') throw Error(`Missing identity sequence ${name(t)}.${a.name}`);
      sql += ` GENERATED ${a.identity === 'a' ? 'ALWAYS' : 'BY DEFAULT'} AS IDENTITY (SEQUENCE NAME ${name(s)} ${seqOptions(s)})`;
    } else if (a.generated) {
      if (a.generated !== 's') throw Error('Unsupported generated column');
      sql += ` GENERATED ALWAYS AS (${a.default}) STORED`;
    } else if (a.default != null) sql += ` DEFAULT ${a.default}`;
    if (a.notnull) sql += ' NOT NULL';
    return '  ' + sql;
  });
  return `CREATE TABLE ${name(t)} (\n${cols.join(',\n')}\n)${t.options ? ' WITH (' + t.options.join(',') + ')' : ''};`;
}
function render(isApp) {
  const include = s => app(s) === isApp;
  const tables = c.tables.filter(t => include(t.schema));
  const funcs = c.functions.filter(f => include(f.schema));
  const out = ['-- Generated by generate.cjs from Production catalog metadata only.',
    '-- No business rows, auth users, credentials, tokens, sequence current values or storage objects.',
    '-- Never apply this snapshot to Production or a populated application schema.',
    'BEGIN;', 'SET LOCAL search_path = public, extensions;', 'SET LOCAL check_function_bodies = false;'];
  if (isApp) {
    out.push(`DO $guard$ BEGIN
 IF current_setting('root_ops.empty_preview_baseline', true) IS DISTINCT FROM 'on' THEN
  RAISE EXCEPTION 'Fresh Preview baseline requires explicit session opt-in';
 END IF;
 IF EXISTS (SELECT 1 FROM pg_class c JOIN pg_namespace n ON n.oid=c.relnamespace WHERE n.nspname='public' AND c.relkind IN ('r','p','v','m','S'))
 OR EXISTS (SELECT 1 FROM pg_proc p JOIN pg_namespace n ON n.oid=p.pronamespace WHERE n.nspname='public' AND NOT EXISTS (SELECT 1 FROM pg_depend d WHERE d.classid='pg_proc'::regclass AND d.objid=p.oid AND d.deptype='e')) THEN
  RAISE EXCEPTION 'Application schema is not empty; refusing baseline';
 END IF;
 IF to_regclass('auth.users') IS NULL OR to_regclass('storage.objects') IS NULL THEN
  RAISE EXCEPTION 'Supabase platform schema is required';
 END IF;
END $guard$;`);
  } else {
    out.push('-- LOCAL TEST PLATFORM CONTRACT ONLY. Never install over managed Supabase schemas.');
    for (const r of e.roles.filter(r => !['postgres','pg_database_owner'].includes(r.name)))
      out.push(`CREATE ROLE ${q(r.name)} NOLOGIN ${r.inherit ? 'INHERIT' : 'NOINHERIT'} ${r.bypassrls ? 'BYPASSRLS' : 'NOBYPASSRLS'};`);
    out.push('CREATE SCHEMA auth;', 'CREATE SCHEMA storage;', 'CREATE SCHEMA extensions;');
    for (const t of c.types || []) {
      if (t.kind !== 'e') throw Error('Domain requires explicit renderer');
      out.push(`CREATE TYPE ${name(t)} AS ENUM (${t.labels.map(lit).join(', ')});`);
    }
  }
  for (const s of c.sequences.filter(s => include(s.schema) && s.dependency !== 'i'))
    out.push(`CREATE SEQUENCE ${name(s)} AS ${s.type} ${seqOptions(s)};`);
  out.push(...tables.map(tableSQL));
  out.push(...funcs.map(f => terminate(f.definition)));
  for (const t of tables) {
    for (const co of (t.constraints || []).filter(co=>co.type !== 'f'))
      out.push(`ALTER TABLE ${name(t)} ADD CONSTRAINT ${q(co.name)} ${co.definition};`);
    const backed = new Set((t.constraints || []).map(co => co.index).filter(Boolean));
    for (const i of t.indexes || []) {
      if (!i.valid) throw Error(`Invalid index ${i.name}`);
      if (!backed.has(i.name)) out.push(terminate(i.definition));
    }
    const rel = e.relations.find(r => r.schema === t.schema && r.name === t.name);
    if (rel.kind !== 'r' || rel.partition || rel.persistence !== 'p' || rel.tablespace !== '0') throw Error(`Unsupported table properties ${name(t)}`);
    if (rel.replica_identity !== 'd') out.push(`ALTER TABLE ${name(t)} REPLICA IDENTITY ${ {f:'FULL',n:'NOTHING'}[rel.replica_identity] || (()=>{throw Error('Replica identity index requires renderer')})() };`);
    out.push(`ALTER TABLE ${name(t)} ${t.rls ? 'ENABLE' : 'DISABLE'} ROW LEVEL SECURITY;`);
    out.push(`ALTER TABLE ${name(t)} ${t.force_rls ? 'FORCE' : 'NO FORCE'} ROW LEVEL SECURITY;`);
  }
  for (const t of tables) for (const co of (t.constraints || []).filter(co=>co.type === 'f'))
    out.push(`ALTER TABLE ${name(t)} ADD CONSTRAINT ${q(co.name)} ${co.definition};`);
  for (const s of c.sequences.filter(s => include(s.schema) && s.dependency === 'a'))
    out.push(`ALTER SEQUENCE ${name(s)} OWNED BY ${q(s.table_schema)}.${q(s.table)}.${q(s.column)};`);
  // The app owns one Auth trigger and six Storage policies, not the platform schema.
  for (const t of c.triggers.filter(t => isApp ? t.schema === 'public' || t.name === 'on_auth_user_created_create_org' : t.schema !== 'public' && t.name !== 'on_auth_user_created_create_org')) {
    out.push(terminate(t.definition));
    if (isApp && t.schema === 'auth' && t.table === 'users' && t.name === 'on_auth_user_created_create_org') {
      // CREATE TRIGGER defaults to origin-enabled. Hosted postgres has TRIGGER
      // privilege, not ownership of Supabase's auth.users; do not ALTER it.
      if (t.enabled !== 'O') throw Error('Managed Auth trigger needs a separately reviewed non-default state');
      out.push(`DO $auth_trigger_state$ BEGIN
 IF NOT EXISTS (SELECT 1 FROM pg_catalog.pg_trigger
  WHERE tgrelid = 'auth.users'::regclass AND tgname = 'on_auth_user_created_create_org'
   AND NOT tgisinternal AND tgenabled = 'O'
   AND tgfoid = 'public.handle_new_user_create_org()'::regprocedure) THEN
  RAISE EXCEPTION 'Managed Auth signup trigger does not match the required enabled state';
 END IF;
END $auth_trigger_state$;`);
      continue;
    }
    const enable = {O:'ENABLE',D:'DISABLE',R:'ENABLE REPLICA',A:'ENABLE ALWAYS'}[t.enabled];
    out.push(`ALTER TABLE ${q(t.schema)}.${q(t.table)} ${enable} TRIGGER ${q(t.name)};`);
  }
  for (const p of c.policies.filter(p => isApp ? p.schemaname === 'public' || p.schemaname === 'storage' : p.schemaname === 'auth')) {
    out.push(`CREATE POLICY ${q(p.policyname)} ON ${q(p.schemaname)}.${q(p.tablename)} AS ${p.permissive} FOR ${p.cmd} TO ${p.roles.map(r => role(r === 'public' ? 'PUBLIC' : r)).join(', ')}${p.qual ? ' USING (' + p.qual + ')' : ''}${p.with_check ? ' WITH CHECK (' + p.with_check + ')' : ''};`);
  }
  for (const t of tables) {
    out.push(`ALTER TABLE ${name(t)} OWNER TO ${q(t.owner)};`, ...acl('TABLE',name(t),t.acl));
  }
  for (const f of funcs) {
    const target = `${name(f)}(${f.signature})`;
    out.push(`ALTER FUNCTION ${target} OWNER TO ${q(f.owner)};`, ...acl('FUNCTION', target, f.acl));
  }
  for (const s of c.sequences.filter(s => include(s.schema))) {
    out.push(`ALTER SEQUENCE ${name(s)} OWNER TO ${q(s.owner)};`, ...acl('SEQUENCE',name(s),e.sequences.find(x=>x.schema===s.schema && x.name===s.name).acl));
  }
  for (const s of c.schemas.filter(s=>include(s.name)))
    out.push(`ALTER SCHEMA ${q(s.name)} OWNER TO ${q(s.owner)};`, ...acl('SCHEMA',q(s.name),s.acl));
  // A hosted platform already supplies managed-role defaults. The local-only
  // platform contract seeds them; the application restore can only verify them.
  for (const d of c.defaults.filter(d=>include(d.schema) || !isApp && managedPublicDefault(d))) {
    if (isApp && managedPublicDefault(d)) {
      out.push(managedDefaultAssertion(d));
      continue;
    }
    const kind = {r:'TABLES',f:'FUNCTIONS',S:'SEQUENCES'}[d.type];
    if (!kind) throw Error('Unsupported default ACL');
    for (const r of ['PUBLIC', ...e.roles.map(r=>r.name)])
      out.push(`ALTER DEFAULT PRIVILEGES FOR ROLE ${q(d.owner)} IN SCHEMA ${q(d.schema)} REVOKE ALL ON ${kind} FROM ${role(r)};`);
    for (const a of d.acl || [])
      out.push(`ALTER DEFAULT PRIVILEGES FOR ROLE ${q(d.owner)} IN SCHEMA ${q(d.schema)} GRANT ${a.privilege} ON ${kind} TO ${role(a.grantee)}${a.grantable?' WITH GRANT OPTION':''};`);
  }
  if (isApp) {
    out.push('-- Declarative bucket configuration only; no object bytes or object records.');
    out.push(`DO $buckets$ BEGIN IF EXISTS (SELECT 1 FROM storage.buckets) THEN RAISE EXCEPTION 'Expected empty Preview bucket configuration'; END IF; END $buckets$;`);
    for (const b of c.buckets)
      out.push(`INSERT INTO storage.buckets (id,name,public,file_size_limit,allowed_mime_types) VALUES (${lit(b.id)},${lit(b.name)},${b.public},${b.file_size_limit || 'NULL'},${b.allowed_mime_types ? 'ARRAY[' + b.allowed_mime_types.map(lit).join(',') + ']::text[]' : 'NULL'});`);
  }
  out.push('COMMIT;', '');
  return out.join('\n');
}
if (e.column_acl) throw Error('Column ACLs require renderer');
if (c.views) throw Error('Views require renderer');
fs.writeFileSync(path.join(root,'local-platform.sql'),render(false));
fs.writeFileSync(path.join(root,'migrations/00000000000000_root_ops_schema_baseline.sql'),render(true));
console.log('Rendered canonical application baseline and catalog-derived local platform contract.');
